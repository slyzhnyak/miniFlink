(* ============================================================
   Ctx_store (v5) — domain-local storage.

   На OCaml 5 домены исполняются параллельно. Глобальный [ref] был бы
   общим на все домены, и одновременные [with_context] из разных
   доменов затёрли бы контекст друг друга. [Domain.DLS] даёт каждому
   домену собственную ячейку — изоляция без блокировок.

   Ячейка инициализируется [None] (контекст не установлен → дефолт).
   Контекст НЕ наследуется при [Domain.spawn]: новый домен видит [None]
   — см. пояснение в ctx_store.mli, почему это корректно для текущего
   использования.

   Граница: [Domain.DLS] защищает от гонок МЕЖДУ доменами (наш случай).
   Внутри одного домена несколько системных потоков (Thread), которые
   конкурентно трогают одну DLS-ячейку, не синхронизированы (известный
   нюанс рантайма). У нас это не возникает: managed-state с durable-
   контекстом используется в одном потоке исполнения пайплайна, а
   [with_context] save/restore не пересекается между потоками. *)

let key : Obj.t option Domain.DLS.key =
  Domain.DLS.new_key (fun () -> None)

let get () = Domain.DLS.get key
let set v = Domain.DLS.set key v
